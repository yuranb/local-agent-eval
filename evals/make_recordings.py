"""Generate fixture recordings from evals/cases.jsonl.

These are NOT real model responses — they are hand-derived "ideal model"
trajectories: a turn with the expected tool call, then a final answer built
from the REAL tool output where a tool is involved. They exist so the CI gate
job can exercise the whole pipeline without Ollama (DECISIONS.md D3).

Re-run after editing cases.jsonl:
    python -m evals.make_recordings
"""
from __future__ import annotations

import json
from pathlib import Path

from agent.tools import add_workdays, calculator, search_docs
from evals.recording import load_recordings
from evals.run_eval import DEFAULT_CASES, DEFAULT_RECORDINGS, load_cases
from evals.scoring import answer_ok

NOTE = (
    "Fixture, not a real model response. Generated by evals/make_recordings.py "
    "as an ideal trajectory: expected tool call, then a final answer derived "
    "from the real tool output. See DECISIONS.md D3."
)


def tool_call_turn(name: str, arguments: dict) -> dict:
    return {
        "role": "assistant",
        "content": "",
        "tool_calls": [{"function": {"name": name, "arguments": arguments}}],
    }


def fixture_answer(case: dict) -> str:
    """Build a plausible final answer for a case using REAL tool output."""
    rule = case["answer_rule"]
    if case["category"] == "search_docs":
        query = case["expected_args"]["search_docs"]["query"]
        snippets = search_docs(query, top_k=5)["snippets"]
        for snippet in snippets:  # first snippet whose text satisfies the rule
            if answer_ok(rule, snippet["text"]):
                return f"According to the docs: \"{snippet['text']}\""
        raise ValueError(f"{case['id']}: no snippet satisfies the answer rule")

    if case["category"] == "calculator":
        args = case["expected_args"]["calculator"]
        value = calculator(args["expression"])["value"]
        return f"The result of {args['expression']} is {value}."

    if case["category"] == "add_workdays":
        args = case["expected_args"]["add_workdays"]
        result = add_workdays(args["date_str"], args["days"])
        return (
            f"The resulting date is {result['result_date']} "
            f"({result['result_weekday']})."
        )

    # no_tool: no tool output to lean on, state the rule's expected value.
    if rule["type"] == "contains":
        return f"The answer is {rule['value']}."
    # Regex rules: try the pattern itself, then a stripped variant (word-boundary
    # anchors don't match their own literal text). Raise loudly if neither works.
    for candidate in (rule["value"], rule["value"].replace("\\b", "")):
        if answer_ok(rule, candidate):
            return candidate
    raise ValueError(f"{case['id']}: cannot build fixture text for regex {rule['value']!r}")


def build_turns(case: dict) -> list:
    turns = []
    for tool, arguments in case["expected_args"].items():
        turns.append(tool_call_turn(tool, arguments))
    final = fixture_answer(case)
    if not answer_ok(case["answer_rule"], final):
        raise ValueError(
            f"{case['id']}: generated fixture answer fails its own rule: {final!r}"
        )
    turns.append({"role": "assistant", "content": final})
    return turns


def main() -> int:
    cases = load_cases(DEFAULT_CASES)
    DEFAULT_RECORDINGS.mkdir(parents=True, exist_ok=True)
    for case in cases:
        payload = {
            "case_id": case["id"],
            "source": "fixture",
            "note": NOTE,
            "turns": build_turns(case),
        }
        path = DEFAULT_RECORDINGS / f"{case['id']}.json"
        path.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    print(f"wrote {len(cases)} fixture recordings to {DEFAULT_RECORDINGS}")

    # Sanity check: everything we just wrote must load and be replausible.
    loaded = load_recordings(DEFAULT_RECORDINGS)
    missing = [c["id"] for c in cases if c["id"] not in loaded]
    if missing:
        raise SystemExit(f"self-check failed, missing: {missing}")
    print("self-check ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
